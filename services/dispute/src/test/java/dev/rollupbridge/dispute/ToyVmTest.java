package dev.rollupbridge.dispute;

import static org.assertj.core.api.Assertions.assertThat;

import com.fasterxml.jackson.databind.JsonNode;
import dev.rollupbridge.core.Bytes32;
import dev.rollupbridge.dispute.vm.Program;
import dev.rollupbridge.dispute.vm.Program.Instruction;
import dev.rollupbridge.dispute.vm.ToyVm;
import dev.rollupbridge.dispute.vm.Trace;
import dev.rollupbridge.dispute.vm.VmState;
import java.util.HashSet;
import java.util.Random;
import java.util.Set;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

class ToyVmTest {
    private static final long MAX = -1L; // 2^64 - 1 as an unsigned long

    @Test
    @DisplayName("the all-zero state hashes to keccak256 of 160 zero bytes (the same pinned value as the Solidity test)")
    void zeroStateHash() {
        assertThat(VmState.zero().hash())
                .isEqualTo(Bytes32.of("0xdfded4ed5ac76ba7379cfe7b3b0f53e768dca8d45a34854e649cfc3c18cbd9cd"));
    }

    @Test
    void everyOpcodeDoesWhatTheTableSays() {
        assertThat(ToyVm.step(Program.of(Instruction.mov(2, 77)), VmState.of(0, 1, 1, 1, 1))).isEqualTo(VmState.of(1, 1, 1, 77, 1));
        assertThat(ToyVm.step(Program.of(Instruction.add(0, 1)), VmState.of(0, 5, 7, 0, 0))).isEqualTo(VmState.of(1, 12, 7, 0, 0));
        assertThat(ToyVm.step(Program.of(Instruction.sub(3, 2)), VmState.of(0, 0, 0, 4, 10))).isEqualTo(VmState.of(1, 0, 0, 4, 6));
        assertThat(ToyVm.step(Program.of(Instruction.mul(1, 2)), VmState.of(0, 0, 6, 7, 0))).isEqualTo(VmState.of(1, 0, 42, 7, 0));
        assertThat(ToyVm.step(Program.of(Instruction.jnz(2, 9)), VmState.of(0, 0, 0, 1, 0))).isEqualTo(VmState.of(9, 0, 0, 1, 0));
        assertThat(ToyVm.step(Program.of(Instruction.jnz(2, 9)), VmState.of(0, 5, 5, 0, 5))).isEqualTo(VmState.of(1, 5, 5, 0, 5));
        assertThat(ToyVm.step(Program.of(Instruction.halt()), VmState.of(0, 1, 2, 3, 4))).isEqualTo(VmState.of(0, 1, 2, 3, 4));
    }

    @Test
    void arithmeticWrapsModulo2Pow64LikeSolidityUint64() {
        assertThat(ToyVm.step(Program.of(Instruction.add(0, 1)), VmState.of(0, MAX, 2, 0, 0))).isEqualTo(VmState.of(1, 1, 2, 0, 0));
        assertThat(ToyVm.step(Program.of(Instruction.sub(0, 1)), VmState.of(0, 1, 2, 0, 0))).isEqualTo(VmState.of(1, MAX, 2, 0, 0));
        assertThat(ToyVm.step(Program.of(Instruction.mul(0, 1)), VmState.of(0, MAX, 2, 0, 0))).isEqualTo(VmState.of(1, MAX - 1, 2, 0, 0));
    }

    @Test
    void trapsBehaveLikeHalt() {
        VmState s = VmState.of(0, 1, 2, 3, 4);
        assertThat(ToyVm.step(Program.of(new Instruction(6, 0, 0, 1)), s)).isEqualTo(s);
        assertThat(ToyVm.step(Program.of(new Instruction(255, 0, 0, 1)), s)).isEqualTo(s);
        assertThat(ToyVm.step(Program.of(Instruction.mov(4, 9)), s)).isEqualTo(s);
        assertThat(ToyVm.step(Program.of(Instruction.add(0, 4)), s)).isEqualTo(s);
        assertThat(ToyVm.step(Program.of(Instruction.jnz(200, 0)), s)).isEqualTo(s);
        Program mov = Program.of(Instruction.mov(0, 1));
        assertThat(ToyVm.step(mov, VmState.of(1, 5, 6, 7, 8))).isEqualTo(VmState.of(1, 5, 6, 7, 8));
        assertThat(ToyVm.step(mov, VmState.of(MAX, 5, 6, 7, 8))).isEqualTo(VmState.of(MAX, 5, 6, 7, 8));
        assertThat(ToyVm.step(Program.fromBytes(new byte[0]), s)).isEqualTo(s);
    }

    @Test
    void aTrailingPartialInstructionDoesNotExist() {
        byte[] code = new byte[Program.INSTRUCTION_SIZE + 3];
        System.arraycopy(Program.of(Instruction.mov(0, 5)).code(), 0, code, 0, Program.INSTRUCTION_SIZE);
        Program p = Program.fromBytes(code);
        assertThat(p.instructionCount()).isEqualTo(1);
        assertThat(ToyVm.step(p, VmState.zero())).isEqualTo(VmState.of(1, 5, 0, 0, 0));
        assertThat(ToyVm.step(p, VmState.of(1, 0, 0, 0, 0))).isEqualTo(VmState.of(1, 0, 0, 0, 0));
    }

    @Test
    void wellFormedness() {
        assertThat(Program.fromBytes(new byte[0]).isWellFormed()).isFalse();
        assertThat(Program.of(Instruction.halt()).isWellFormed()).isTrue();
        assertThat(Program.fromBytes(new byte[12]).isWellFormed()).isFalse();
        assertThat(Program.fromBytes(new byte[11 * 64]).isWellFormed()).isTrue();
        assertThat(Program.fromBytes(new byte[11 * 65]).isWellFormed()).isFalse();
    }

    @Test
    void sumLoopAndFactorialCompute() {
        VmState end = ToyVm.run(Program.sumLoop(10), VmState.zero(), 3 + 3 * 10);
        assertThat(end.r1()).isEqualTo(55);
        assertThat(ToyVm.run(Program.sumLoop(10), VmState.zero(), 1_000_000)).isEqualTo(end); // HALT is a fixed point
        assertThat(ToyVm.run(Program.factorial(10), VmState.zero(), 200).r1()).isEqualTo(3_628_800);
    }

    // ----- differential tests against the Solidity vectors -----

    @Test
    @DisplayName("424 pseudo-random cases generated by the REAL Solidity ToyVM.step: Java gives the same post-state and hashes")
    void javaStepEqualsSolidityStepOnTheCommittedVectors() {
        JsonNode cases = TestData.vectors().get("stepCases");
        assertThat(cases.size()).isEqualTo(424);
        Set<Integer> opcodesSeen = new HashSet<>();
        int changed = 0;
        for (JsonNode c : cases) {
            Program program = Program.fromBytes(dev.rollupbridge.core.Hex.decode(c.get("program").asText()));
            VmState pre = TestData.state(c.get("pre"));
            VmState expectedPost = TestData.state(c.get("post"));

            VmState post = ToyVm.step(program, pre);
            assertThat(post).as("post-state of %s from %s", c.get("program").asText(), pre).isEqualTo(expectedPost);
            assertThat(pre.hash()).isEqualTo(TestData.hash(c.get("preHash")));
            assertThat(post.hash()).isEqualTo(TestData.hash(c.get("postHash")));

            if (Long.compareUnsigned(pre.pc(), program.instructionCount()) < 0) {
                opcodesSeen.add(program.code()[(int) pre.pc() * Program.INSTRUCTION_SIZE] & 0xff);
            }
            if (!post.equals(pre)) {
                changed++;
            }
        }
        // the vectors exercise every opcode, valid and invalid ones, and are not mostly no-ops
        assertThat(opcodesSeen).contains(0, 1, 2, 3, 4, 5, 6, 7);
        assertThat(changed).isGreaterThan(200);
    }

    @Test
    @DisplayName("whole executions: the state hash after every step equals the Solidity trace")
    void javaTracesEqualSolidityTraces() {
        for (JsonNode t : TestData.vectors().get("traces")) {
            Program program = Program.fromBytes(dev.rollupbridge.core.Hex.decode(t.get("program").asText()));
            int steps = t.get("steps").asInt();
            Trace trace = new Trace(program, VmState.zero());
            for (int i = 0; i <= steps; i++) {
                assertThat(trace.hashAt(i)).as("%s step %d", t.get("name").asText(), i).isEqualTo(TestData.hash(t.get("hashes").get(i)));
            }
            assertThat(trace.at(steps)).isEqualTo(TestData.state(t.get("final")));
        }
    }

    // ----- Trace -----

    @Test
    void traceRandomAccessAgreesWithPlainExecutionAcrossCheckpointBoundaries() {
        Program p = counting();
        Random rnd = new Random(7);
        Trace trace = new Trace(p, VmState.zero());
        for (int i = 0; i < 300; i++) {
            long n = rnd.nextInt(30_000);
            assertThat(trace.at(n)).as("step %d", n).isEqualTo(ToyVm.run(p, VmState.zero(), n));
        }
        // boundaries exactly at and around the checkpoint spacing, asked out of order
        for (long n : new long[] {4095, 4096, 4097, 8192, 0, 1, 12288}) {
            assertThat(trace.at(n)).isEqualTo(ToyVm.run(p, VmState.zero(), n));
        }
    }

    @Test
    void aHaltedMachineIsAnsweredInConstantTimeForAbsurdlyLateSteps() {
        Trace trace = new Trace(Program.sumLoop(5), VmState.zero());
        VmState end = trace.at(18);
        assertThat(end.r1()).isEqualTo(15);
        assertThat(trace.at(1L << 50)).isEqualTo(end);
        assertThat(trace.at(Long.MAX_VALUE)).isEqualTo(end);
        assertThat(trace.at(17)).isNotEqualTo(end);
    }

    /** r0 += r1 forever, with r1 = 3: never halts, every state differs. */
    static Program counting() {
        return Program.of(Instruction.mov(1, 3), Instruction.add(0, 1), Instruction.jnz(1, 1));
    }
}
